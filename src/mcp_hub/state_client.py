"""Decoded async Redis port.

redis-py shares command annotations between synchronous and asynchronous clients.
This boundary narrows that union once; the application always supplies an async
client with decode_responses=True. Tests use the same port and real Lua scripts.
"""

from __future__ import annotations

import builtins
from collections.abc import AsyncIterator, Awaitable
from typing import Any, Protocol, cast

from redis.asyncio.client import Pipeline


class StateClient(Protocol):
    def eval(self, script: str, numkeys: int, *args: Any) -> Awaitable[Any]: ...
    def get(self, name: str) -> Awaitable[str | None]: ...
    def mget(self, names: list[str]) -> Awaitable[list[str | None]]: ...
    def getdel(self, name: str) -> Awaitable[str | None]: ...
    def set(self, name: str, value: Any, **kwargs: Any) -> Awaitable[bool | None]: ...
    def delete(self, *names: str) -> Awaitable[int]: ...
    def expire(self, name: str, time: int) -> Awaitable[bool]: ...
    def type(self, name: str) -> Awaitable[str]: ...
    def hget(self, name: str, key: str) -> Awaitable[str | None]: ...
    def hgetall(self, name: str) -> Awaitable[dict[str, str]]: ...
    def hset(self, name: str, key: str, value: Any) -> Awaitable[int]: ...
    def hsetnx(self, name: str, key: str, value: Any) -> Awaitable[bool]: ...
    def hexists(self, name: str, key: str) -> Awaitable[bool]: ...
    def hdel(self, name: str, *keys: str) -> Awaitable[int]: ...
    def sadd(self, name: str, *values: str) -> Awaitable[int]: ...
    def srem(self, name: str, *values: str) -> Awaitable[int]: ...
    def smembers(self, name: str) -> Awaitable[builtins.set[str]]: ...
    def sismember(self, name: str, value: str) -> Awaitable[bool]: ...
    def scard(self, name: str) -> Awaitable[int]: ...
    def llen(self, name: str) -> Awaitable[int]: ...
    def lindex(self, name: str, index: int) -> Awaitable[str | None]: ...
    def lrange(self, name: str, start: int, end: int) -> Awaitable[list[str]]: ...
    def rpush(self, name: str, *values: str) -> Awaitable[int]: ...
    def zrange(self, name: str, start: int, end: int) -> Awaitable[list[str]]: ...
    def zremrangebyscore(self, name: str, minimum: Any, maximum: Any) -> Awaitable[int]: ...
    def ping(self) -> Awaitable[bool]: ...
    def info(self, section: str) -> Awaitable[dict[str, Any]]: ...
    def config_get(self, pattern: str) -> Awaitable[dict[str, str]]: ...
    def memory_usage(self, name: str) -> Awaitable[int | None]: ...
    def scan_iter(self, **kwargs: Any) -> AsyncIterator[str]: ...
    def pipeline(self, transaction: bool = True) -> Pipeline: ...
    def aclose(self) -> Awaitable[None]: ...


def async_state(client: Any) -> StateClient:
    return cast(StateClient, client)
